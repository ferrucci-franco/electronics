let LANG = 'fr';

function t(key, vars){
  const dict = I18N[LANG] || I18N.fr;
  const s = dict[key] !== undefined ? dict[key] : (I18N.fr[key] !== undefined ? I18N.fr[key] : key);
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : '{' + k + '}')) : s;
}

function applyStaticI18n(){
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.documentElement.lang = LANG;
}

// Changement de langue en direct (cahier §8) : les libellés statiques sont
// réécrits, puis chaque panneau se re-rend — c'est là que les infobulles et les
// textes calculés (readouts, légendes) reprennent la nouvelle langue.
function setLang(code){
  if (!I18N[code]) return;
  LANG = code;
  applyStaticI18n();
  if (typeof App !== 'undefined') App.refreshLang();
}
